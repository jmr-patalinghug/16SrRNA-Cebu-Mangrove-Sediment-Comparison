# -----------------------------
# 1. Clean metadata columns
# -----------------------------

meta_rda$ForestGroup <- trimws(as.character(meta_rda$`forest-type`))

meta_rda$ForestGroup <- ifelse(
  meta_rda$ForestGroup == "natural", "Natural",
  ifelse(meta_rda$ForestGroup == "planted", "Planted", meta_rda$ForestGroup)
)

meta_rda$Site <- trimws(as.character(meta_rda$site))
meta_rda$Island <- trimws(as.character(meta_rda$island))

# Correct site spelling if needed
meta_rda$Site[meta_rda$Site == "Madredijos"] <- "Madridejos"


# -----------------------------
# 2. Extract sample scores
# -----------------------------

site_scores <- as.data.frame(
  scores(rda_reduced, display = "sites", choices = 1:2, scaling = 2)
)

site_scores$SampleID <- rownames(site_scores)

# Add metadata by matching sample names
site_scores$ForestGroup <- meta_rda[site_scores$SampleID, "ForestGroup"]
site_scores$Site <- meta_rda[site_scores$SampleID, "Site"]
site_scores$Island <- meta_rda[site_scores$SampleID, "Island"]

# Convert to factors for cleaner legends
site_scores$ForestGroup <- factor(
  site_scores$ForestGroup,
  levels = c("Natural", "Planted")
)

site_scores$Site <- factor(
  site_scores$Site,
  levels = c("Madridejos", "Panitugan", "Sta-Fe", "OIWS-1", "OIWS-2")
)


# -----------------------------
# 3. Extract environmental arrows
# -----------------------------

env_scores <- as.data.frame(
  scores(rda_reduced, display = "bp", choices = 1:2, scaling = 2)
)

env_scores$Variable_raw <- rownames(env_scores)

# Clean raw variable names
env_scores$Variable_raw <- gsub("`", "", env_scores$Variable_raw)
env_scores$Variable_raw <- trimws(env_scores$Variable_raw)

# Create clean labels
env_scores$Variable <- env_scores$Variable_raw

env_scores$Variable[env_scores$Variable_raw == "mean-soil-salinity"] <- "Salinity"
env_scores$Variable[env_scores$Variable_raw == "mean-phospho"] <- "Phosphorus"
env_scores$Variable[env_scores$Variable_raw == "mean-om"] <- "Organic matter"


# -----------------------------
# 4. Scale arrows for plotting
# -----------------------------

arrow_multiplier <- 0.8 * min(
  max(abs(site_scores$RDA1), na.rm = TRUE) / max(abs(env_scores$RDA1), na.rm = TRUE),
  max(abs(site_scores$RDA2), na.rm = TRUE) / max(abs(env_scores$RDA2), na.rm = TRUE)
)

env_scores$RDA1 <- env_scores$RDA1 * arrow_multiplier
env_scores$RDA2 <- env_scores$RDA2 * arrow_multiplier


# -----------------------------
# 5. Position arrow labels
# -----------------------------

# Default: place labels beyond arrow tips
env_scores$label_mult <- 1.12

# Bring Salinity and Phosphorus closer to their arrow tips
env_scores$label_mult[
  env_scores$Variable %in% c("Salinity", "Phosphorus")
] <- 1.06

env_scores$label_x <- env_scores$RDA1 * env_scores$label_mult
env_scores$label_y <- env_scores$RDA2 * env_scores$label_mult

# Nudge Organic matter slightly downward
env_scores$label_y[env_scores$Variable == "Organic matter"] <-
  env_scores$label_y[env_scores$Variable == "Organic matter"] - 0.02

# Nudge Salinity slightly upward
env_scores$label_y[env_scores$Variable == "Salinity"] <-
  env_scores$label_y[env_scores$Variable == "Salinity"] + 0.02

# Nudge Phosphorus slightly left and downward
env_scores$label_x[env_scores$Variable == "Phosphorus"] <-
  env_scores$label_x[env_scores$Variable == "Phosphorus"] - 0.03

env_scores$label_y[env_scores$Variable == "Phosphorus"] <-
  env_scores$label_y[env_scores$Variable == "Phosphorus"] - 0.01

# -----------------------------
# 6. Percent variation explained
# -----------------------------

eig <- rda_reduced$CCA$eig

rda1_pct <- round(100 * eig[1] / rda_reduced$tot.chi, 1)
rda2_pct <- round(100 * eig[2] / rda_reduced$tot.chi, 1)


# -----------------------------
# 7. Quick checks
# -----------------------------

table(site_scores$ForestGroup, useNA = "ifany")
table(site_scores$Site, useNA = "ifany")

env_scores

