### RDA analysis; Final####
library(vegan)
library(glmnet)
library(ggplot2)
library(ggrepel)



# Read feature table
#Feature table used here is one where taxa with unassigned phylum were removed along with mitochondria and chloroplast reads hence, "clean"
asv <- read.table(
  "feature-table-clean.tsv",
  header = TRUE,
  row.names = 1,
  sep = "\t",
  skip = 1,
  check.names = FALSE,
  comment.char = ""
)

# Transpose so samples are rows and ASVs/features are columns
asv_t <- t(asv)

# Read metadata
meta <- read.table(
  "usc-sediment-metadata.tsv",
  header = TRUE,
  row.names = 1,
  sep = "\t",
  check.names = FALSE,
  comment.char = "",
  quote = ""
)

# Check if asv table and metadata table match
nrow(asv_t)
rownames(asv_t)

nrow(meta)
rownames(meta)

length(intersect(rownames(asv_t), rownames(meta)))

setdiff(rownames(asv_t), rownames(meta))
setdiff(rownames(meta), rownames(asv_t))

# Match the samples
common_samples <- intersect(rownames(asv_t), rownames(meta))

## The following steps will prepare the asv table for any downstream statistical analysis such as if you want to do permutation analysis manually without using distances generated by QIIME2. 
# Note that samples = rows, ASVs = columns

asv_perm <- asv_t[common_samples, ] #subset only the samples common to asv table and metadata
meta_perm <- meta[common_samples, ] #subset only the samples common to metadata and asv table

all(rownames(asv_perm) == rownames(meta_perm)) #check
nrow(asv_perm)

# Remove samples with zero total abundance
asv_perm <- asv_perm[rowSums(asv_perm) > 0, , drop = FALSE]

# Re-match metadata after removing any empty samples
meta_perm <- meta_perm[rownames(asv_perm), , drop = FALSE]

# Remove ASVs/features with zero total abundance
asv_perm <- asv_perm[, colSums(asv_perm) > 0, drop = FALSE]

# Confirm
all(rownames(asv_perm) == rownames(meta_perm))
nrow(asv_perm)


# Hellinger transform the raw ASV counts 
#Because RDA is a linear ordination method based on Euclidean distances, ASV abundance data were Hellinger-transformed prior to analysis following Legendre and Gallagher (2001), which recommended this transformation for community composition data used in linear ordination.

asv_hell <- decostand(asv_perm, method = "hellinger")

# Preparing the environmental variables data 

env_vars <- c("mean-soil-salinity",
              "mean-soil-temp",
              "mean-nitrogen",
              "mean-phospho",
              "mean-om",
              "mean-iron",
              "mean-potassium")

# Make metadata copy
meta_rda <- meta_perm

# Make sure environmental variables are numeric
meta_rda[, env_vars] <- lapply(meta_rda[, env_vars], as.numeric)

# Scale environmental variables #very important! AS we are comparing parameters with different scales of measure like temperature and iron content
meta_rda[, env_vars] <- scale(meta_rda[, env_vars])


## Check which variables are correlated
#make envi data variable
env_data <- meta_perm[, env_vars]

# Make sure they are numeric
env_data[] <- lapply(env_data, as.numeric)

# Correlation matrix
cor_mat <- cor(env_data, use = "complete.obs", method = "pearson")

round(cor_mat, 2)

## visualize collinearity

threshold <- 0.7

collinear_pairs <- which(
  abs(cor_mat) > threshold & upper.tri(cor_mat),
  arr.ind = TRUE
)

collinear_table <- data.frame(
  variable1 = rownames(cor_mat)[collinear_pairs[, 1]],
  variable2 = colnames(cor_mat)[collinear_pairs[, 2]],
  correlation = cor_mat[collinear_pairs]
)

collinear_table

collinear_vars <- unique(c(
  collinear_table$variable1,
  collinear_table$variable2
))

# View correlation matrix
# only once
library(corrplot)

corrplot(
  cor_mat,
  method = "color",
  type = "upper",
  addCoef.col = "black",
  tl.col = "black",
  tl.srt = 45
)

#Oh no, many are correlated. I will try lasso tool for variable selection and if it won't work; I will pick the most biologically relevant variable

## LASSO variable selection
# Remove rows with missing environmental data

complete_rows <- complete.cases(env_data)


x <- env_data[complete_rows, ]
y <- asv_hell[complete_rows, ]

# Convert environmental variables to numeric matrix and scale them
x <- as.matrix(x)
x <- scale(x)

# Convert community table to matrix
y <- as.matrix(y)

# Remove ASVs/features with zero abundance across all retained samples
y <- y[, colSums(y) > 0]

#Lasso

set.seed(123)

cv_lasso <- cv.glmnet(
  x,
  y,
  family = "mgaussian",
  alpha = 1,
  standardize = FALSE,
  nfolds = 5
)

lasso_coef_min <- coef(cv_lasso, s = "lambda.min")

selected_lasso_min <- unique(unlist(lapply(lasso_coef_min, function(m) {
  rownames(m)[as.numeric(m) != 0]
})))

selected_lasso_min <- setdiff(selected_lasso_min, "(Intercept)")

selected_lasso_min

# Lasso did not work; guess we have to manually pick
# Let's check whether environmental parameters are significantly different across sites
## PERMANOVA on Euclidean distance

# Scale variables because they are on different units
env_scaled <- scale(env_data)
env_dist <- dist(env_scaled, method = "euclidean")

adonis_env_site <- adonis2(
  env_dist ~ site,
  data = meta_perm,
  permutations = 999
)

adonis_env_site

## PERMDISP
disp_env_site <- betadisper(env_dist, meta_perm$site)
anova(disp_env_site)
plot(disp_env_site)

### Pairwise PERMANOVA among sites
# To identify which site pairs differ in their overall multivariate soil chemistry.
#Use the pairwise function manually created during beta diversity analysis

pairwise_soil_site <- pairwise_permanova(
  distance_matrix = env_dist,
  group = meta_perm$site,
  permutations = 999,
  p_adjust_method = "BH"
)

pairwise_soil_site[order(pairwise_soil_site$p_adj), ]


### PERMANOVA was underpowered so let's biologically pick 
# Highly correlated variables: P, Fe and K; N and OM (expected because N and C cycling are coupled)
# I'll pick salinity, P and OMG as envi variables
# Salinity is not correlated with other nutrients and is a known predictor for coastal ecosystems
# P is related to nutrient availability for mangroves
# OM because it also indicates carbon cycling potential

rda_reduced <- rda(
  asv_hell ~ `mean-soil-salinity` +
    `mean-phospho` +
    `mean-om`,
  data = meta_rda
)

vif.cca(rda_reduced) #variance inflation factor for multicollinearity; values should ideally be less than 2.5 to convey that there is little to no variance due to collinearity across explanatory variables 

anova(rda_reduced, permutations = 999)
anova(rda_reduced, by = "term", permutations = 999)
anova(rda_reduced, by = "axis", permutations = 999)

plot(rda_reduced) #exploratory plotting


anova(rda_reduced, by = "margin", permutations = 999)
#OM was significant but overall RDA model was not 



